"""What each component promises to do (Protocols).

Ticket: BK-1   Tier: A
Design: docs/design.md
"""

from typing import Protocol


class Intake(Protocol):
    def load(self, spec_path, project_path): ...


class AgentRunner(Protocol):
    def run(self, role, prompt, workdir, timeout_s): ...


class TestRunner(Protocol):
    def run(self, workdir, commands): ...


class Workspace(Protocol):
    def ensure(self, ticket): ...
    def diff(self, ticket): ...
    def head_commit(self, ticket): ...
    def remove(self, ticket): ...


class Store(Protocol):
    def create_ticket(self, ticket): ...
    def get(self, ticket_id): ...
    def transition(self, ticket_id, expected_from, to, detail=""): ...
    def record_run(self, run): ...
    def record_findings(self, ticket_id, findings): ...
    def list_by_status(self, status): ...
    def history(self, ticket_id): ...


class RetryPolicy(Protocol):
    def next_delay(self, attempt, exit_code): ...


class Notifier(Protocol):
    def send(self, title, body): ...

